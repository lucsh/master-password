import './sha256';

const passLenght = document.querySelector('input[name="lenght"]');
const useSymbols = document.querySelector('input[name="symbols"]');
const useCaps = document.querySelector('input[name="caps"]');
const seed = document.querySelector('input[name="seed"]');
const hiddenSeed = document.querySelector('#hidden-seed');
const newPass = document.querySelector('input[name="new-pass"]');
const copyButton = document.querySelector('#btn_copy');
const status = document.querySelector('#copy-status');
const lengthError = document.querySelector('#length-error');
const theme = document.querySelector('#theme');

function getPass(seed, hidden) {
    let contrasena = '';

    const len = passLenght.value;
    // eslint-disable-next-line no-undef
    let prepass = sha256(`${seed}${hidden}`);

    if (useSymbols.checked) {
        const vocales = prepass.match(/[aeiou]/gi);

        const syms = '{!#$%&()*+,-./:;<=>?@[{}]^_|~}';
        const index = Math.round((vocales.length * syms.length) / 100);
        prepass =
            prepass.slice(0, len / 3) +
            syms[index] +
            prepass.slice(len / 3, (len * 2) / 3) +
            syms[index + 2] +
            prepass.slice((len * 2) / 3, len);
    }
    let middle = prepass.slice(len / 3, (len * 2) / 3)
    if (useCaps.checked) {
        if (middle.substring(1,len / 3).match(/^[0-9]+$/) != null){
            //#$4237 => $A23L
            const letters="IDKFAHOLYV"
            const posa=middle[1]
            const posb=middle.slice(-1)
             middle=`${middle[0]}${letters[posa]}${middle.substring(1,middle.length-2)}${letters[posb]}`
        }

        prepass =
            prepass.slice(0, len / 3) +
            middle.toUpperCase() +
            prepass.slice((len * 2) / 3, len);
    }
    contrasena = prepass.slice(0, len);

    return contrasena;
}


function getNewPass() {
    status.textContent = '';
    const valid = /^\d+$/.test(passLenght.value) && Number(passLenght.value) >= 1 && Number(passLenght.value) <= 64;
    lengthError.textContent = valid ? '' : 'Enter a whole number from 1 to 64.';
    passLenght.setAttribute('aria-invalid', String(!valid));
    document.querySelector('#options-summary').textContent = valid
        ? `${passLenght.value} characters${useCaps.checked ? ' · Aa' : ''}${useSymbols.checked ? ' · Symbols' : ''}`
        : 'Check password length';
    newPass.value = '';
    if (valid && (seed.value || hiddenSeed.value)) {
        try { newPass.value = getPass(seed.value, hiddenSeed.value); }
        catch (_) { status.textContent = 'This combination cannot be generated by the current algorithm. Try another seed.'; }
    }
    copyButton.disabled = !newPass.value;
}

function bindReveal(buttonId, input) {
    const button = document.querySelector(buttonId);
    button.addEventListener('click', () => {
        const show = input.type === 'password';
        input.type = show ? 'text' : 'password';
        button.textContent = show ? 'Hide' : 'Show';
        button.setAttribute('aria-pressed', String(show));
    });
}
bindReveal('#btn_peek', hiddenSeed);
bindReveal('#btn_result_peek', newPass);
[seed, hiddenSeed, passLenght].forEach((input) => input.addEventListener('input', getNewPass));
[useSymbols, useCaps].forEach((input) => input.addEventListener('change', getNewPass));
document.querySelector('.generator').addEventListener('submit', (event) => event.preventDefault());
copyButton.addEventListener('click', async () => {
    const password = newPass.value;
    if (!password) return;
    try {
        await navigator.clipboard.writeText(password);
        if (newPass.value === password) status.textContent = 'Copied to clipboard.';
    } catch (_) {
        status.textContent = 'Copy unavailable. Use Show, then select and copy the password.';
    }
});

const systemTheme = window.matchMedia('(prefers-color-scheme: dark)');
try { theme.value = localStorage.getItem('password-theme') || 'system'; } catch (_) { theme.value = 'system'; }
if (!['system', 'light', 'dark'].includes(theme.value)) theme.value = 'system';
function applyTheme() {
    const dark = theme.value === 'dark' || (theme.value === 'system' && systemTheme.matches);
    document.documentElement.dataset.theme = dark ? 'dark' : 'light';
    document.querySelector('meta[name="theme-color"]').content = dark ? '#181a17' : '#f4f4ed';
}
theme.addEventListener('change', () => {
    try { localStorage.setItem('password-theme', theme.value); } catch (_) { /* Theme still works without storage. */ }
    applyTheme();
});
systemTheme.addEventListener('change', applyTheme);
applyTheme();
getNewPass();
